/** Full catalog grouped by category. */
export const CATALOG: {
  [K in ComponentCategory]: ComponentByCategory[K][];
} = {
  cpu: CPUS,
  gpu: GPUS,
  motherboard: MOTHERBOARDS,
  ram: RAMS,
  storage: STORAGES,
  psu: PSUS,
  case: CASES,
  cooler: COOLERS,
  fans: FANS,
};

/** Flat list of every catalog entry. */
export const ALL_COMPONENTS: PCComponent[] = [
  ...CPUS,
  ...GPUS,
  ...MOTHERBOARDS,
  ...RAMS,
  ...STORAGES,
  ...PSUS,
  ...CASES,
  ...COOLERS,
  ...FANS,
];

const COMPONENT_INDEX = new Map<string, PCComponent>(
  ALL_COMPONENTS.map((component) => [component.id, component]),
);

/** Looks a component up by id. Returns `undefined` for unknown ids. */
export function getComponentById(id: string | null | undefined): PCComponent | undefined {
  if (!id) return undefined;
  return COMPONENT_INDEX.get(id);
}

/** Type-safe lookup that also validates the category. */
export function getComponentByIdAs<K extends ComponentCategory>(
  category: K,
  id: string | null | undefined,
): ComponentByCategory[K] | null {
  const found = getComponentById(id);
  if (!found || found.category !== category) return null;
  return found as ComponentByCategory[K];
}

export function getComponentsByCategory<K extends ComponentCategory>(
  category: K,
): ComponentByCategory[K][] {
  return CATALOG[category];
}

/** Distinct brands available inside a category, sorted alphabetically. */
export function getBrands(category: ComponentCategory): string[] {
  const brands = new Set(CATALOG[category].map((component) => component.brand));
  return Array.from(brands).sort((a, b) => a.localeCompare(b));
}

/** Min/max price found inside a category, used to seed the range filter. */
export function getPriceRange(category: ComponentCategory): { min: number; max: number } {
  const prices = CATALOG[category].map((component) => component.price);
  if (prices.length === 0) return { min: 0, max: 0 };
  return { min: Math.min(...prices), max: Math.max(...prices) };
}
